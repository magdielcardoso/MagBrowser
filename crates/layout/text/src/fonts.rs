//! Bitmap data for the engine's built-in font.
//!
//! The engine ships exactly one typeface: a monospace bitmap face covering
//! printable ASCII (`U+0020..=U+007E`). There is no TrueType/OpenType shaping
//! and no font fallback chain yet; this table is the base text renderer used
//! by both layout and paint.
//!
//! # Provenance
//!
//! The glyph shapes are the well-known public-domain 8x8 console font
//! (`font8x8_basic`, originally by Daniel Hepper and long predating it in
//! public-domain terminal ROMs). The canonical table stores the leftmost pixel
//! in bit 0 of each row byte; the table below has been bit-reversed so that
//! **bit 7 is the leftmost pixel**, matching [`crate::Glyph::rows`].
//!
//! # Metrics
//!
//! The font is defined on an 8x16 cell: glyphs are 8 pixels wide and 8 pixels
//! tall, rasterised into the top part of the cell below the ascent line (the
//! bottom 4 pixels of the 16-pixel cell are the descent, which is empty in this
//! face). At a request size of `px` pixels the cell scales uniformly by
//! `px / 16`.

/// Width of the glyph bitmap in pixels at the design size.
pub(crate) const GLYPH_WIDTH: u8 = 8;

/// Height of the glyph bitmap in pixels at the design size.
pub(crate) const GLYPH_HEIGHT: u8 = 8;

/// Width of the em cell in font units (pixels at a 16px request size).
pub(crate) const CELL_WIDTH: f32 = 8.0;

/// Height of the em cell in font units (pixels at a 16px request size).
pub(crate) const CELL_HEIGHT: f32 = 16.0;

/// First code point covered by the bitmap table.
pub(crate) const FIRST_ASCII: char = ' ';

/// Number of code points covered by the bitmap table.
pub(crate) const GLYPH_COUNT: usize = 95;

