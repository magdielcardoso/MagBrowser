/// Replacement glyph drawn for characters the face does not cover.
///
/// A hollow box, the conventional "missing glyph" shape. It is used for every
/// non-ASCII, non-control character (see [`crate::Font::glyph`]).
pub(crate) const FALLBACK_GLYPH: [u8; 8] = [0xFF, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81, 0xFF];

/// Returns the bitmap rows for a printable ASCII character, if covered.
pub(crate) fn ascii_rows(c: char) -> Option<&'static [u8]> {
    let code = c as u32;
    let first = FIRST_ASCII as u32;
    let last = first + GLYPH_COUNT as u32 - 1;
    if !(first..=last).contains(&code) {
        return None;
    }
    let index = (code - first) as usize;
    Some(GLYPHS_8X8[index].as_slice())
}
